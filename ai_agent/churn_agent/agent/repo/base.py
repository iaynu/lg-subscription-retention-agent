from __future__ import annotations
from typing import Protocol

class Repository(Protocol):
    def recent_actions(self, subscription_id: str, as_of_date: str, days: int = 90) -> list[dict]: ...
    def log_action(self, row: dict) -> dict: ...
    def list_actions(self, subscription_id: str) -> list[dict]: ...
    def put_result(self, request_id: str, result: dict) -> None: ...
    def get_result(self, request_id: str) -> dict | None: ...
